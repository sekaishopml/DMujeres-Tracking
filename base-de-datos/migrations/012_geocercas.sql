-- 012: geocercas (polígonos dibujados en el mapa del panel) con historial de
-- quién las creó y quién las editó. Con ellas se detectan llegadas y salidas.
BEGIN;
CREATE TABLE IF NOT EXISTS operations.dmt_geocerca (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre         TEXT NOT NULL,
    tipo           TEXT NOT NULL,
    puntos         JSONB NOT NULL,
    centro_lat     DOUBLE PRECISION NOT NULL,
    centro_lon     DOUBLE PRECISION NOT NULL,
    activo         BOOLEAN NOT NULL DEFAULT TRUE,
    creado_por     TEXT NOT NULL,
    editado_por    TEXT,
    creado_en      TIMESTAMPTZ NOT NULL DEFAULT now(),
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_dmt_geocerca_tipo CHECK (tipo IN ('casa', 'cliente', 'oficina', 'cc', 'na')),
    CONSTRAINT ck_dmt_geocerca_puntos CHECK (jsonb_typeof(puntos) = 'array' AND jsonb_array_length(puntos) BETWEEN 3 AND 200)
);
CREATE TABLE IF NOT EXISTS operations.dmt_geocerca_historial (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    geocerca_id  BIGINT NOT NULL REFERENCES operations.dmt_geocerca(id) ON DELETE CASCADE,
    accion       TEXT NOT NULL,
    quien        TEXT NOT NULL,
    usuario_id   BIGINT REFERENCES iam.dmt_usuario(id) ON DELETE SET NULL,
    cambios      JSONB NOT NULL DEFAULT '{}'::jsonb,
    ocurrido_en  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_dmt_geocerca_historial_accion CHECK (accion IN ('crear', 'editar', 'eliminar', 'restaurar'))
);
CREATE INDEX IF NOT EXISTS ix_dmt_geocerca_historial ON operations.dmt_geocerca_historial (geocerca_id, ocurrido_en DESC);
GRANT SELECT ON operations.dmt_geocerca, operations.dmt_geocerca_historial TO dmt_consulta;
COMMIT;
